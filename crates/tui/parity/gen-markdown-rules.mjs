// node parity/gen-markdown-rules.mjs > src/components/markdown_rules.rs (marked@18.0.11 resolvable):
// emits marked's gfm rules as Rust consts, JS regex syntax rewritten for fancy-regex.
import { Lexer } from "marked";
const R = Lexer.rules;
// JS whitespace (\s) and dot differ from Rust's; spell them out.
const WS = "\\t\\n\\x0B\\x0C\\r \\xA0\\x{1680}\\x{2000}-\\x{200A}\\x{2028}\\x{2029}\\x{202F}\\x{205F}\\x{3000}\\x{FEFF}";
function conv(src) {
  let out = "", inClass = false;
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (c === "\\") {
      const n = src[i + 1];
      i++;
      if (n === "w") out += inClass ? "0-9A-Za-z_" : "[0-9A-Za-z_]";
      else if (n === "d") out += inClass ? "0-9" : "[0-9]";
      else if (n === "s") out += inClass ? WS : "[" + WS + "]";
      else if (n === "S") out += inClass ? "\\S" : "[^" + WS + "]";
      else if (n === "b") out += "(?:(?<=[0-9A-Za-z_])(?![0-9A-Za-z_])|(?<![0-9A-Za-z_])(?=[0-9A-Za-z_]))";
      else if (n === "/") out += "/";
      else if (n === "u") { const h = src.slice(i + 1, i + 5); out += `\\x{${h}}`; i += 4; }
      else out += "\\" + n;
      continue;
    }
    if (c === "[" && !inClass) inClass = true;
    else if (c === "]" && inClass) inClass = false;
    else if (c === "\t") { out += "\\t"; continue; }
    else if (c === "." && !inClass) { out += "[^\\n\\r\\x{2028}\\x{2029}]"; continue; }
    out += c;
  }
  return out;
}
const pick = { block: ["blockquote","code","def","fences","heading","hr","html","lheading","list","newline","paragraph","table","text"],
  inline: ["_backpedal","anyPunctuation","autolink","blockSkip","br","code","escape","link","nolink","punctuation","reflink","reflinkSearch","tag","text","url","emStrongLDelim"] };
var rs = "// Generated by parity/gen-markdown-rules.mjs from marked 18.0.11 (gfm rules). Do not edit.\n\n";
const H = String.fromCharCode(35, 35), Q = String.fromCharCode(34);
for (const lvl of ["block", "inline"]) for (const n of pick[lvl]) {
  const { source: src, flags } = R[lvl].gfm[n];
  const name = (lvl + "_" + n.replace(/^_/, "").replace(/[A-Z]/g, (m) => "_" + m.toLowerCase())).toUpperCase();
  const pre = flags.includes("i") ? "(?i)" : "";
  rs += "pub const " + name + ": &str = r" + H + Q + pre + conv(src) + Q + H + ";\n";
}
process.stdout.write(rs);
