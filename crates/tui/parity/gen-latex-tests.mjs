// Port of upstream test/latex.test.ts to Rust: node parity/gen-latex-tests.mjs <ref/packages/tui> > tests/latex.rs
// Runs the upstream test file with node:test / node:assert stubbed so every
// assert.strictEqual(renderLatex(source, options), expected) is recorded with its test name.
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const root = process.argv[2];
const latex = await import(pathToFileURL(`${root}/src/latex.ts`).href);
let last;
globalThis.__latexStub = {
	renderLatex: (source, options) => {
		last = { source, display: options?.display === true };
		return latex.renderLatex(source, options);
	},
};
const names = [];
const tests = [];
let current;
globalThis.__testStub = {
	describe: (name, fn) => {
		names.push(name);
		fn();
		names.pop();
	},
	it: (name, fn) => {
		current = { name: [...names, name].join(" / "), cases: [] };
		tests.push(current);
		fn();
	},
};
globalThis.__assertStub = {
	strictEqual: (actual, expected) => {
		if (actual !== expected) throw new Error(`upstream test fails: ${JSON.stringify(last)} ${JSON.stringify(actual)}`);
		current.cases.push({ ...last, expected });
		last = undefined;
	},
};
let source = readFileSync(`${root}/test/latex.test.ts`, "utf8")
	.replace(/^import assert from "node:assert";$/m, "const assert = globalThis.__assertStub;")
	.replace(/^import \{ describe, it \} from "node:test";$/m, "const { describe, it } = globalThis.__testStub;")
	.replace(/^import \{ renderLatex \} from "..\/src\/index.ts";$/m, "const { renderLatex } = globalThis.__latexStub;");
if (source.includes("from \"")) throw new Error("unexpected import in latex.test.ts");
const file = join(mkdtempSync(join(tmpdir(), "latex-test-")), "latex.test.ts");
writeFileSync(file, source);
await import(pathToFileURL(file).href);

const lit = (s) => JSON.stringify(s).replace(/\\u00([0-9a-f]{2})/g, "\\u{$1}");
const rust = (v) => (v === undefined ? "None" : `Some(${lit(v)})`);
let out = `//! Port of upstream test/latex.test.ts (generated by parity/gen-latex-tests.mjs; one Rust test per
//! upstream \`it\`, same cases and expectations).

use pi_tui::latex::render_latex;

#[track_caller]
fn check(cases: &[(&str, bool, Option<&str>)]) {
    for &(source, display, expected) in cases {
        assert_eq!(render_latex(source, display).as_deref(), expected, "source {source:?} display {display}");
    }
}
`;
const used = new Map();
for (const t of tests) {
	let id = t.name.replace(/^renderLatex \/ /, "").toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "").slice(0, 80).replace(/_$/, "");
	const n = used.get(id) ?? 0;
	used.set(id, n + 1);
	if (n) id += `_${n + 1}`;
	out += `\n/// ${t.name.replace(/\n/g, " ")}\n#[test]\nfn ${id}() {\n    check(&[\n`;
	for (const c of t.cases) out += `        (${lit(c.source)}, ${c.display}, ${rust(c.expected)}),\n`;
	out += `    ]);\n}\n`;
}
process.stdout.write(out);
