import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
const require = createRequire(join(process.cwd(), "x.js"));
const { eastAsianWidth } = await import(require.resolve("get-east-asian-width"));
const props = {
	zero_width: /^(?:\p{Default_Ignorable_Code_Point}|\p{Control}|\p{Mark}|\p{Surrogate})$/v,
	non_printing: /^(?:\p{Default_Ignorable_Code_Point}|\p{Control}|\p{Format}|\p{Mark}|\p{Surrogate})$/v,
	mark: /^\p{Mark}$/v,
	spacing_mark:
		/^(?:[\p{Spacing_Mark}--[\u1734\u302E\u302F]]|[\u065F\u0F7F\u102B\u102C\u1031\u1033-\u1035\u1038\u103A-\u103E])$/v,
	cjk_break:
		/[\p{Script_Extensions=Han}\p{Script_Extensions=Hiragana}\p{Script_Extensions=Katakana}\p{Script_Extensions=Hangul}\p{Script_Extensions=Bopomofo}]/u,
	punctuation: /\p{Punctuation}/u,
	white_space: /\s/u,
	letter: /\p{L}/u,
	number: /\p{N}/u,
	symbol: /\p{S}/u,
	uppercase: /\p{Lu}/u,
};
const str = (cp) => String.fromCodePoint(cp);
function ranges(test) {
	const out = [];
	let start = -1;
	for (let cp = 0; cp <= 0x110000; cp++) {
		const ok = cp < 0x110000 && !(cp >= 0xd800 && cp <= 0xdfff) && test(cp);
		if (ok && start < 0) start = cp;
		if (!ok && start >= 0) {
			out.push([start, cp - 1]);
			start = -1;
		}
	}
	return out;
}
let rs = `// Generated by parity/gen-tables.mjs from Node ${process.versions.node} (Unicode ${process.versions.unicode}). Do not edit.\n\n`;
const emit = (name, rgs) => {
	rs += `pub(crate) static ${name.toUpperCase()}: &[(u32, u32)] = &[\n`;
	for (const [a, b] of rgs) rs += `    (0x${a.toString(16)}, 0x${b.toString(16)}),\n`;
	rs += '];\n\n';
};
for (const [name, re] of Object.entries(props)) emit(name, ranges((cp) => re.test(str(cp))));
emit("east_asian_wide", ranges((cp) => eastAsianWidth(cp) === 2));

const rgi = /^\p{RGI_Emoji}$/v;
const set = new Set();
const add = (s) => {
	if (rgi.test(s)) set.add(s);
};
for (let cp = 0; cp < 0x110000; cp++) {
	if (cp >= 0xd800 && cp <= 0xdfff) continue;
	const s = str(cp);
	add(s);
	add(`${s}\uFE0F`);
	add(`${s}\uFE0F\u20E3`);
	for (let m = 0x1f3fb; m <= 0x1f3ff; m++) add(s + str(m));
}
for (let a = 0x1f1e6; a <= 0x1f1ff; a++) for (let b = 0x1f1e6; b <= 0x1f1ff; b++) add(str(a) + str(b));
const dir = process.argv[2];
const tag = (t) => [...t].map((c) => str(0xe0000 + c.charCodeAt(0))).join('');
for (const t of ['gbeng', 'gbsct', 'gbwls']) add(`\u{1F3F4}${tag(t)}\u{E007F}`);
for (const f of ['emoji-zwj-sequences.txt', 'emoji-variation-sequences.txt']) {
	for (const line of readFileSync(join(dir, f), 'utf8').split('\n')) {
		const m = line.match(/^([0-9A-F]+(?: [0-9A-F]+)*)\s*;/);
		if (!m) continue;
		add(String.fromCodePoint(...m[1].split(' ').map((h) => parseInt(h, 16))));
	}
}
const singles = [];
const multi = [];
for (const s of set) {
	const cps = [...s].map((c) => c.codePointAt(0));
	if (cps.length === 1) singles.push(cps[0]);
	else multi.push(s);
}
singles.sort((a, b) => a - b);
const sr = [];
for (const cp of singles) {
	const l = sr[sr.length - 1];
	if (l && l[1] === cp - 1) l[1] = cp;
	else sr.push([cp, cp]);
}
emit('rgi_emoji_single', sr);
const enc = (s) => [...s].map((c) => `\\u{${c.codePointAt(0).toString(16)}}`).join('');
multi.sort();
rs += 'pub(crate) static RGI_EMOJI_MULTI: &[&str] = &[\n';
for (const s of multi) rs += `    "${enc(s)}",\n`;
rs += '];\n';
process.stdout.write(rs);
console.error(`rgi ${set.size} (${multi.length} multi)`);
